#!/usr/bin/env node
// Outsider Inside — one scene, two aspects. index.html is the only source; this writes the Shorts twin.
//
//   node aspect.mjs <project> [--out shorts]
//
// Writes <project>/shorts/ as a complete HyperFrames project (so check / snapshot / render / legibility /
// facts verify all run on it unchanged):
//   index.html     = <project>/index.html with 1080×1920 size and <html data-aspect="9x16">; scene CSS gives the
//                    portrait layout under  :root[data-aspect="9x16"] …  (and .only-169 / .only-916 helpers)
//   scene-facts.json (sources_md re-pointed one level up), .facts-cache, look.json (+ "aspect"), hyperframes.json,
//   package.json, and an `assets` link (junction on Windows) to <project>/assets when that folder exists.
// Run AFTER `facts.mjs apply` (the Shorts copy carries the applied texts). Never edit shorts/index.html by hand.
import fs from 'node:fs';
import path from 'node:path';

const args = process.argv.slice(2);
const proj = path.resolve(args.find((a) => !a.startsWith('--')) || '.');
const outName = (() => { const i = args.indexOf('--out'); return i >= 0 ? args[i + 1] : 'shorts'; })();
const out = path.join(proj, outName);
const src = path.join(proj, 'index.html');
if (!fs.existsSync(src)) { console.error(`✖ missing ${src}`); process.exit(2); }

let html = fs.readFileSync(src, 'utf8');
const swaps = [
  [/<html([^>]*?)>/, (m, a) => `<html${a.replace(/\s*data-aspect="[^"]*"/, '')} data-aspect="9x16">`],
  [/<meta name="viewport" content="width=1920, height=1080" \/>/, '<meta name="viewport" content="width=1080, height=1920" />'],
  [/data-width="1920" data-height="1080"/, 'data-width="1080" data-height="1920"'],
];
for (const [re, rep] of swaps) {
  if (!re.test(html)) { console.error(`✖ index.html lacks ${re} — is it an Outsider Inside scene?`); process.exit(2); }
  html = html.replace(re, rep);
}
if (!/data-aspect="9x16"\]/.test(html)) console.warn('⚠ no [data-aspect="9x16"] rules in the scene CSS — the portrait layout will just be the landscape one squeezed');
html = html.replace(/<head>/, '<head>\n    <!-- GENERATED by tools/aspect.mjs from ../index.html — edit the source, not this file -->');

fs.mkdirSync(out, { recursive: true });
fs.writeFileSync(path.join(out, 'index.html'), html);
for (const f of ['hyperframes.json', 'package.json']) if (fs.existsSync(path.join(proj, f))) fs.copyFileSync(path.join(proj, f), path.join(out, f));
const sf = path.join(proj, 'scene-facts.json');
if (fs.existsSync(sf)) {
  const j = JSON.parse(fs.readFileSync(sf, 'utf8'));
  if (j.sources_md && !path.isAbsolute(j.sources_md)) j.sources_md = path.posix.join('..', j.sources_md);
  fs.writeFileSync(path.join(out, 'scene-facts.json'), JSON.stringify(j, null, 2) + '\n');
}
const lk = path.join(proj, 'look.json');
if (fs.existsSync(lk)) fs.writeFileSync(path.join(out, 'look.json'), JSON.stringify({ ...JSON.parse(fs.readFileSync(lk, 'utf8')), aspect: '9x16' }, null, 2) + '\n');
const cache = path.join(proj, '.facts-cache');
if (fs.existsSync(cache)) fs.cpSync(cache, path.join(out, '.facts-cache'), { recursive: true });
const assets = path.join(proj, 'assets'), link = path.join(out, 'assets');
if (fs.existsSync(assets) && !fs.existsSync(link)) {
  try { fs.symlinkSync(path.relative(out, assets) || assets, link, 'junction'); }
  catch { fs.symlinkSync(assets, link, 'junction'); }
}
console.log(`shorts → ${path.relative(process.cwd(), out) || out}/index.html (1080×1920)`);
